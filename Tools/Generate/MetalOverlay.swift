import Foundation

// The experimental Metal trait swaps raylib's rlgl implementation for rlmt. That swap cannot be done
// from outside: rcore.c includes "rlgl.h" with quotes, which always finds the header next to it, and
// SwiftPM has no configure step. So the generator writes patched copies of rcore.c and the RGFW
// platform into Sources/CRaylib/metal, and `--check` keeps them in step with the submodule.
//
// Every patch states how many times its text must appear, so a raylib update that moves the code
// fails here instead of quietly producing a build that never opens a frame.

private struct Patch {
    let find: String
    let replace: String
    let count: Int
}

private func applying(_ patches: [Patch], to source: String, file: String) throws -> String {
    var result = source
    for patch in patches {
        let found = result.components(separatedBy: patch.find).count - 1
        guard found == patch.count else {
            throw GenerateError("\(file): expected \(patch.count) of \(patch.find.debugDescription), found \(found)")
        }
        result = result.replacingOccurrences(of: patch.find, with: patch.replace)
    }
    return result
}

private func overlay(_ path: String, root: URL, patches: [Patch], suffix: String = "") throws -> String {
    let source = try String(contentsOf: root.appending(path: "Sources/CRaylib/raylib/src/\(path)"), encoding: .utf8)
    let header = "// Generated by swaylib-generate from raylib's \(path), for the Metal trait. Do not edit.\n\n"
    return header + (try applying(patches, to: source, file: path)) + suffix
}

/// raylib's `rcore.c`, using rlmt and opening and closing a Metal frame around the drawing.
func emitMetalCore(root: URL) throws -> String {
    try overlay(
        "rcore.c",
        root: root,
        patches: [
            Patch(
                find: "#define RLGL_IMPLEMENTATION\n#include \"rlgl.h\"",
                replace: "#include \"../raylib-backends/backends/rlmt/src/rlmt.h\"",
                count: 1
            ),
            Patch(
                find: "CORE.Time.previous = CORE.Time.current;\n\n    rlLoadIdentity();",
                replace: """
                    CORE.Time.previous = CORE.Time.current;

                        // Metal: the layer does not follow the window by itself.
                        if (CORE.Window.resizedLastFrame) rlmtResizeSurface(CORE.Window.currentFbo.width, CORE.Window.currentFbo.height);
                        rlBeginFrame();

                        rlLoadIdentity();
                    """,
                count: 1
            ),
            Patch(
                find: "#endif\n\n#if !SUPPORT_CUSTOM_FRAME_CONTROL\n    SwapScreenBuffer();",
                replace: "#endif\n\n    rlEndFrame();\n\n#if !SUPPORT_CUSTOM_FRAME_CONTROL\n    SwapScreenBuffer();",
                count: 1
            ),
            Patch(
                find: "#include \"platforms/rcore_desktop_rgfw.c\"",
                replace: "#include \"rcore_desktop_rgfw.c\"",
                count: 1
            ),
        ]
    )
}

/// raylib's RGFW platform, creating a window without an OpenGL context and handing it to rlmt.
func emitMetalPlatform(root: URL) throws -> String {
    // rlmt finds the NSWindow through this GLFW function, which is the only thing it needs from a
    // windowing library. Swaylib has no GLFW on macOS, so RGFW answers instead.
    let cocoaWindow = """

        // rlmt asks GLFW for the NSWindow to attach its CAMetalLayer to. On macOS Swaylib uses RGFW.
        void *glfwGetCocoaWindow(void *window)
        {
            return RGFW_window_getWindow_OSX((RGFW_window *)window);
        }

        """
    return try overlay(
        "platforms/rcore_desktop_rgfw.c",
        root: root,
        patches: [
            // This copy is not next to raylib's external/ directory, but that is on the header path.
            Patch(find: "\"../external/", replace: "\"external/", count: 4),
            Patch(find: "flags | RGFW_windowOpenGL);", replace: "flags);", count: 1),
            Patch(find: "RGFW_window_swapInterval_OpenGL(platform.window, ", replace: "rlSetVSync(", count: 4),
            Patch(
                find: "RGFW_window_swapBuffers_OpenGL(platform.window);",
                replace: "rlSwapScreenBuffers();",
                count: 1
            ),
            Patch(
                find: "RGFW_window_makeCurrentWindow_OpenGL(platform.window);",
                replace: "rlmtSetGLFWWindow(platform.window);",
                count: 1
            ),
        ],
        suffix: cocoaWindow
    )
}
